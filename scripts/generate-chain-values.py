#!/usr/bin/env python3
"""Generate this one-shot trial's C constants from the canonical plan."""
import argparse
import json
from pathlib import Path
import re
import zlib


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('plan', type=Path)
    parser.add_argument('stage2_stub', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    plan = json.loads(args.plan.read_text())
    nonce = plan['nonce']
    if not re.fullmatch('[0-9a-f]{16}', nonce):
        raise RuntimeError('trial nonce format')
    stub = args.stage2_stub.read_bytes()
    if not 0 < len(stub) <= 512:
        raise RuntimeError('ARM64 handoff stub does not fit its one-sector allocation')
    lines = ['/* Generated by generate-chain-values.py; edit ram-chain-trial.json. */',
             '#ifndef __QUA_TRIAL_VALUES_H', '#define __QUA_TRIAL_VALUES_H',
             '#define QUA_TRIAL_NONCE ' + json.dumps(nonce),
             '#define QUA_TRIAL_BOOTARGS ' + json.dumps(plan['normal']['bootargs'] + ' qua_ram_chain=' + nonce)]
    for name, macro in [('kernel', 'KERNEL'), ('dtb', 'DTB'), ('stage2', 'STAGE2'), ('base_env', 'BASE_ENV')]:
        blob = plan['buffers'][name]
        lines += [f'#define QUA_{macro}_BYTES {blob["bytes"]}U',
                  f'#define QUA_{macro}_CRC32 0x{blob["crc32"]}U']
    lines += [f'#define QUA_STAGE2_STUB_BYTES {len(stub)}U',
              f'#define QUA_STAGE2_STUB_CRC32 0x{zlib.crc32(stub):08x}U', '#endif', '']
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines))
    print(f'TRIAL_VALUES_GENERATED nonce={nonce} stub_bytes={len(stub)}')


if __name__ == '__main__':
    main()
